    /** XOR 还原 */
    public static String d(byte[] enc) {
        if (enc == null) return null;
        char[] c = new char[enc.length];
        for (int i = 0; i < enc.length; i++) {
            c[i] = (char) (enc[i] ^ K);
        }
        return new String(c);
    }

